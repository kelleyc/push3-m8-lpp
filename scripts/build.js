#!/usr/bin/env node
/*
 * Build script — regenerates everything under devices/ from core/ + glue/.
 *
 *   node scripts/build.js
 *
 * For each device it writes:
 *   <name>.js      Max `js` bundle: core modules + device glue, one file
 *                  (Max's legacy js engine has no require()).
 *   <name>.maxpat  readable patcher source (open in Max to edit/inspect)
 *   <name>.amxd    the same patcher wrapped as a Max MIDI Effect device
 *
 * The .amxd is NOT frozen. Push 3 Standalone needs the js file inside the
 * device: open the .amxd in Max, click Freeze (snowflake), save. See
 * docs/TEST-PLAN.md.
 *
 * No dependencies.
 */
"use strict";

const fs = require("fs");
const path = require("path");

const ROOT = path.join(__dirname, "..");
const CORE = ["midi-stream.js", "lpp.js", "led-state.js", "palette.js", "push-map.js", "bridge.js"];
const AMXD_MIDI_EFFECT = 0x6d6d6d6d; // 'mmmm'

// ---------------------------------------------------------------------------
// js bundles

function bundle(deviceName, glueFile) {
  const parts = [
    "// " + deviceName + ".js — GENERATED by scripts/build.js. Do not edit here:",
    "// edit core/*.js or glue/" + glueFile + " and rebuild.",
    "// Built " + new Date().toISOString().slice(0, 10) + ".",
    ""
  ];
  for (const f of CORE) {
    parts.push("// ===== core/" + f + " =====");
    parts.push(fs.readFileSync(path.join(ROOT, "core", f), "utf8"));
  }
  parts.push("// ===== glue/" + glueFile + " =====");
  parts.push(fs.readFileSync(path.join(ROOT, "glue", glueFile), "utf8"));
  return parts.join("\n");
}

// ---------------------------------------------------------------------------
// patcher model

function createPatch() {
  const boxes = [];
  const lines = [];
  const banks = [];
  let auto = 0;

  function add(box) {
    if (!box.id) box.id = "obj-" + (++auto);
    boxes.push({ box });
    return box.id;
  }
  function obj(text, x, y, opts) {
    opts = opts || {};
    return add(Object.assign({
      maxclass: "newobj", text, patching_rect: [x, y, opts.w || Math.max(60, text.length * 7 + 16), 22],
      numinlets: opts.inlets == null ? 1 : opts.inlets,
      numoutlets: opts.outlets == null ? 1 : opts.outlets,
      outlettype: opts.outlettype || new Array(opts.outlets == null ? 1 : opts.outlets).fill("")
    }, opts.id ? { id: opts.id } : {}));
  }
  function msg(text, x, y, opts) {
    opts = opts || {};
    return add(Object.assign({
      maxclass: "message", text, patching_rect: [x, y, opts.w || Math.max(40, text.length * 7 + 14), 22],
      numinlets: 2, numoutlets: 1, outlettype: [""]
    }, opts.id ? { id: opts.id } : {}));
  }
  function comment(text, x, y, w, pres) {
    const b = { maxclass: "comment", text, patching_rect: [x, y, w || 400, 20], numinlets: 1, numoutlets: 0 };
    if (pres) { b.presentation = 1; b.presentation_rect = pres; }
    return add(b);
  }
  function param(maxclass, longname, shortname, x, y, opts) {
    opts = opts || {};
    const valueof = Object.assign({
      parameter_longname: longname,
      parameter_shortname: shortname,
      // Live int parameters are capped at 255. Counters must go higher, so
      // numeric readouts are float parameters displayed as integers.
      parameter_type: opts.type == null ? 0 : opts.type,
      parameter_mmin: 0,
      parameter_mmax: opts.max == null ? 999999 : opts.max,
      parameter_unitstyle: opts.type == null ? 1 : 0
    }, opts.enumList ? { parameter_enum: opts.enumList } : {},
    opts.initial != null ? { parameter_initial_enable: 1, parameter_initial: [opts.initial] } : {});
    const outs = { "live.numbox": ["", "float"], "live.toggle": [""], "live.tab": ["", "", "float"], "live.button": [""] }[maxclass] || [""];
    const b = {
      maxclass, varname: longname, parameter_enable: 1,
      patching_rect: [x, y, opts.w || 56, opts.h || 15],
      numinlets: 1, numoutlets: outs.length, outlettype: outs,
      saved_attribute_attributes: { valueof }
    };
    if (maxclass === "live.tab") { b.num_lines_patching = 1; b.num_lines_presentation = 1; }
    if (opts.pres) { b.presentation = 1; b.presentation_rect = opts.pres; }
    return add(b);
  }
  function connect(from, outlet, to, inlet) {
    lines.push({ patchline: { source: [from, outlet || 0], destination: [to, inlet || 0] } });
  }
  function bank(name, longnames) { banks.push({ name, longnames }); }

  function toJSON(meta) {
    const parameterbanks = {};
    banks.forEach((b, i) => {
      const params = b.longnames.slice(0, 8);
      while (params.length < 8) params.push("-");
      parameterbanks[String(i)] = { index: i, name: b.name, parameters: params };
    });
    return {
      patcher: {
        fileversion: 1,
        appversion: { major: 8, minor: 6, revision: 0, architecture: "x64", modernui: 1 },
        classnamespace: "box",
        rect: [100, 100, 980, 640],
        openrect: [0, 0, meta.width || 560, meta.height || 169],
        openinpresentation: 1,
        default_fontsize: 10,
        default_fontface: 0,
        default_fontname: "Arial Bold",
        gridonopen: 1, gridsize: [8, 8], gridsnaponopen: 1, objectsnaponopen: 1,
        statusbarvisible: 2, toolbarvisible: 1,
        boxanimatetime: 500,
        description: meta.description,
        digest: meta.digest,
        tags: "push, m8, launchpad, lpp, liveapi, standalone",
        parameters: Object.keys(parameterbanks).length ? { parameterbanks, inherited_shortname: 1 } : {},
        latency: 0, is_mpe: 0, external_mpe_tuning_enabled: 0,
        minimum_live_version: "", minimum_max_version: "", platform_compatibility: 0,
        project: {
          version: 1, creationdate: 3590052493, modificationdate: 3590052493,
          viewrect: [0, 0, 300, 500], autoorganize: 1, hideprojectwindow: 1, showdependencies: 1,
          autolocalize: 0, contents: { patchers: {} }, layout: {}, searchpath: {}, detailsvisible: 0,
          amxdtype: AMXD_MIDI_EFFECT, readonly: 0, devpathtype: 0, devpath: ".", sortmode: 0,
          viewmode: 0, includepackages: 0
        },
        autosave: 0,
        boxes,
        lines
      }
    };
  }

  return { obj, msg, comment, param, connect, bank, toJSON, boxes, lines };
}

