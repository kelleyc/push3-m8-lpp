function addReadouts(p, js, names, x0, y0, presX0, presY0) {
  const route = p.obj("route " + names.map((n) => n[0]).join(" "), x0, y0, { outlets: names.length + 1 });
  p.connect(js, 1, route, 0);
  names.forEach((r, i) => {
    const col = i % 6;
    const row = Math.floor(i / 6);
    const nb = p.param("live.numbox", r[1], r[2], x0 + i * 64, y0 + 60, {
      type: r[3] ? 2 : 1, enumList: r[3], max: r[3] ? r[3].length - 1 : 999999,
      pres: [presX0 + col * 74, presY0 + row * 40 + 14, 60, 15], w: 60
    });
    p.comment(r[1], x0 + i * 64, y0 + 82, 60, [presX0 + col * 74, presY0 + row * 40, 72, 16]);
    p.connect(route, i, nb, 0);
  });
  return route;
}

function addOutPath(p, js, x, y, pres) {
  const tab = p.param("live.tab", "Out Path", "OutPath", x, y, {
    type: 2, enumList: ["this track", "M8 OUT", "both"], max: 2, initial: 0, w: 150, h: 18, pres
  });
  const prep = p.obj("prepend out_path", x, y + 30);
  p.connect(tab, 0, prep, 0);
  p.connect(prep, 0, js, 0);
  return tab;
}

