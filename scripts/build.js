function writeRelease() {
  const dir = path.join(ROOT, "release");
  fs.mkdirSync(dir, { recursive: true });
  const patch = buildRelease();
  fs.writeFileSync(path.join(dir, "m8-lpp.js"), bundle("m8-lpp", "bridge.glue.js"));
  fs.writeFileSync(path.join(dir, "M8 LPP.maxpat"), JSON.stringify(patch, null, 2) + "\n");
  fs.writeFileSync(path.join(dir, "M8 LPP.amxd"), amxd(patch));
  console.log("built release/ (M8 LPP.amxd, M8 LPP.maxpat, m8-lpp.js)");
}

// ---------------------------------------------------------------------------
// .amxd container: 'ampf' <4> 'mmmm' 'meta' <4> <1> 'ptch' <len> json \0

function amxd(patchJson) {
  const json = Buffer.from(JSON.stringify(patchJson, null, 2) + "\n", "utf8");
  const body = Buffer.concat([json, Buffer.from([0])]);
  const head = Buffer.alloc(32);
  head.write("ampf", 0, "ascii");
  head.writeUInt32LE(4, 4);
  head.write("mmmm", 8, "ascii");
  head.write("meta", 12, "ascii");
  head.writeUInt32LE(4, 16);
  head.writeUInt32LE(1, 20);
  head.write("ptch", 24, "ascii");
  head.writeUInt32LE(body.length, 28);
  return Buffer.concat([head, body]);
}

function writeDevice(name, glue, patchJson) {
  const dir = path.join(ROOT, "devices", name);
  fs.mkdirSync(dir, { recursive: true });
  if (glue) fs.writeFileSync(path.join(dir, name + ".js"), bundle(name, glue));
  fs.writeFileSync(path.join(dir, name + ".maxpat"), JSON.stringify(patchJson, null, 2) + "\n");
  fs.writeFileSync(path.join(dir, name + ".amxd"), amxd(patchJson));
  console.log("built devices/" + name + "/" + (glue ? " (.js, .maxpat, .amxd)" : " (.maxpat, .amxd)"));
}

if (require.main === module) {
  writeDevice("m8-lpp-handshake", "handshake.glue.js", buildHandshake());
  writeDevice("m8-lpp-bridge", "bridge.glue.js", buildBridge());
  writeDevice("m8-lpp-out", null, buildOut());
  writeRelease();
}

module.exports = { createPatch, buildHandshake, buildBridge, buildOut, buildRelease, bundle, amxd };
